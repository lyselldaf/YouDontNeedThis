<#
.SYNOPSIS
Turns the in-game `/ydnt export` result into YouDontNeedThis\SeedData.lua.

.DESCRIPTION
1. In game, with Questie (and its QuestieDB addon) enabled: /ydnt export, wait for "export done", then log out or /reload.
2. Run this script, pointing it at the account-wide saved variables file:
   <WoW Forever>\WTF\Account\<ACCOUNT>\SavedVariables\YouDontNeedThis.lua

.EXAMPLE
.\tools\Build-SeedData.ps1 -SavedVariables "D:\Games\WoW Forever\WTF\Account\MYACCOUNT\SavedVariables\YouDontNeedThis.lua"
#>
param(
    [Parameter(Mandatory = $true)]
    [string]$SavedVariables,

    # Where to write; defaults to the addon's SeedData.lua.
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'

# Resolved here, not as the parameter default: Windows PowerShell 5.1 can leave $PSScriptRoot empty there.
if (-not $OutFile) {
    $scriptDir = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
    $OutFile = Join-Path $scriptDir '..\YouDontNeedThis\SeedData.lua'
}

if (-not (Test-Path -LiteralPath $SavedVariables)) {
    throw "Saved variables file not found: $SavedVariables"
}

$text = [IO.File]::ReadAllText((Resolve-Path -LiteralPath $SavedVariables))
$marker = 'YDNT_Export = '
$start = $text.IndexOf($marker)
if ($start -lt 0) {
    throw "No YDNT_Export found in $SavedVariables. Run /ydnt export in game, then log out or /reload first."
}

# WoW writes each saved variable as a top-level "Name = {...}" block. Take ours up to the next
# top-level assignment (a line starting with an identifier and " = "), or the end of the file.
$body = $text.Substring($start + $marker.Length)
$next = [regex]::Match($body, '(?m)^[A-Za-z_][A-Za-z0-9_]* = ')
if ($next.Success) { $body = $body.Substring(0, $next.Index) }
$body = $body.TrimEnd()

$meta = [regex]::Match($body, '\["source"\] = "([^"]*)"')
$source = if ($meta.Success) { $meta.Groups[1].Value } else { 'QuestieDB' }

$header = @"
-- GENERATED by tools/Build-SeedData.ps1 from the in-game /ydnt export. Do not edit by hand.
--
-- Item -> quest links, quest names and race/class masks extracted from $source
-- (https://github.com/Questie/QuestieDB), which is licensed under the GNU GPL v3.
-- This file is distributed under the same license; see LICENSE.md and CREDITS.md.
--
-- items    = { [itemID] = { questID, ... } }       an item is "not needed" once every listed quest is done
-- quests   = { [questID] = { name, races, classes } }  races/classes are bitmasks, 0 = everyone
-- raceMask = { [raceID] = bit used in races }
-- hidden   = { [questID] = true }                  quests Questie hides as unobtainable; they don't keep an item needed

local _, ns = ...

ns.SeedData =
"@

$outPath = $OutFile
$utf8NoBom = New-Object System.Text.UTF8Encoding $false
[IO.File]::WriteAllText([IO.Path]::GetFullPath($outPath), ($header + ' ' + $body + "`n"), $utf8NoBom)

$items = [regex]::Match($body, '\["items"\] = (\d+)')
$quests = [regex]::Match($body, '\["quests"\] = (\d+)')
Write-Host "Wrote $([IO.Path]::GetFullPath($outPath))"
if ($items.Success -and $quests.Success) {
    Write-Host "$($items.Groups[1].Value) items linked to $($quests.Groups[1].Value) quests (from $source)."
}
